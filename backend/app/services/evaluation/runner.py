"""Runs gates and persists results. Each gate runs in its own session that is rolled back, so the
evaluation never leaves side effects (e.g. retrieval logs) in operational tables."""

from __future__ import annotations

import os
import uuid
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

from sqlalchemy import select

from app.core.config import Settings
from app.db.session import get_sessionmaker
from app.models.evaluation import EvaluationResult, EvaluationRun
from app.services import audit
from app.services.evaluation import gates as g


async def _execute(gate: str, source_dir: Path, provider_configured: bool) -> g.GateOutcome:
    async with get_sessionmaker()() as session:
        try:
            if gate == "G1":
                return await g.g1_pii(session, source_dir)
            if gate == "G2":
                return await g.g2_classification(session, provider_configured)
            if gate == "G3":
                return await g.g3_dedupe(session)
            if gate == "G4":
                return await g.g4_injection(session)
            if gate == "G5":
                return await g.g5_rag(session)
            if gate == "G6":
                return await g.g6_output(session)
            if gate == "G7":
                return await g.g7_performance(session)
            raise ValueError(f"unknown gate {gate}")
        finally:
            await session.rollback()


async def run_gates(gate_ids: list[str], settings: Settings, actor: uuid.UUID | None = None) -> list[EvaluationRun]:
    source_dir = Path(settings.data_source_dir)
    provider_configured = settings.llm_provider != "none" and bool(settings.bedrock_classifier_model_id)
    commit = os.environ.get("APP_GIT_COMMIT")
    runs: list[EvaluationRun] = []
    for gate in gate_ids:
        started = datetime.now(tz=UTC)
        outcome = await _execute(gate, source_dir, provider_configured)
        async with get_sessionmaker()() as session:
            run = EvaluationRun(
                gate=outcome.gate,
                name=outcome.name,
                status=outcome.status,
                dataset=outcome.dataset,
                dataset_size=outcome.dataset_size,
                target=outcome.target,
                metrics=outcome.metrics,
                notes=outcome.notes,
                critical=outcome.critical,
                source_commit=commit,
                triggered_by=actor,
                started_at=started,
                finished_at=datetime.now(tz=UTC),
            )
            session.add(run)
            await session.flush()
            session.add_all(
                EvaluationResult(run_id=run.id, case_id=case_id[:80], passed=passed, detail=detail)
                for case_id, passed, detail in outcome.cases
            )
            await audit.record(
                session, "evaluation.run", actor_user_id=actor, entity_type="evaluation_run", entity_id=str(run.id),
                details={"gate": gate, "status": outcome.status},
            )  # fmt: skip
            await session.commit()
            runs.append(run)
    return runs


async def latest_runs() -> dict[str, EvaluationRun]:
    async with get_sessionmaker()() as session:
        rows = await session.scalars(select(EvaluationRun).order_by(EvaluationRun.started_at))
        return {r.gate: r for r in rows}


def render_report(runs: list[EvaluationRun], failures: dict[str, list[dict[str, Any]]]) -> str:
    lines = [
        "# Evaluation report (G1-G7)",
        "",
        "Generated by `python -m app.cli evaluate`. Every figure below comes from an executed run; parts that need",
        "a model are reported as `not_run`, never estimated.",
        "",
        "| Gate | Name | Status | Dataset size | Key results | Run (UTC) |",
        "|---|---|---|---|---|---|",
    ]
    for r in sorted(runs, key=lambda x: x.gate):
        key = ", ".join(f"{k}={v}" for k, v in r.metrics.items() if not isinstance(v, dict | list) and v is not None)[
            :220
        ]
        lines.append(
            f"| {r.gate} | {r.name} | **{r.status}** | {r.dataset_size} | {key} | "
            f"{(r.finished_at or r.started_at).strftime('%Y-%m-%d %H:%M')} |"
        )
    for r in sorted(runs, key=lambda x: x.gate):
        lines += ["", f"## {r.gate} - {r.name}", "", f"- **Status:** {r.status}", f"- **Dataset:** {r.dataset}",
                  f"- **Target:** {r.target}", f"- **Metrics:** `{r.metrics}`"]  # fmt: skip
        lines += [f"- {n}" for n in r.notes]
        failed = failures.get(r.gate) or []
        if failed:
            lines.append(f"- **Failed cases ({len(failed)}):**")
            lines += [f"  - `{f['case_id']}` {f['detail']}" for f in failed[:30]]
    return "\n".join(lines) + "\n"
