"""Generate the API, database and RBAC reference docs from the code itself.

    cd backend && python ../scripts/generate_reference_docs.py

Needs the same environment as the API (JWT_SECRET, PII_VAULT_KEY, DATABASE_URL); no database
connection is opened. Writes:

    docs/api/README.md          endpoint table (method, path, permission, summary)
    docs/api/openapi.json       the OpenAPI document served at /api/openapi.json
    docs/database/README.md     ER diagrams per domain + table reference
    docs/security/rbac.md       role x permission matrix

Generated from code so the documents cannot drift from what is implemented: re-run after
changing routes, models or roles.
"""

from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from fastapi.routing import APIRoute  # noqa: E402

import app.models  # noqa: E402,F401  (registers every model)
from app.core.rbac import ROLE_PERMISSIONS, Permission  # noqa: E402
from app.db.base import Base  # noqa: E402
from app.main import create_app  # noqa: E402

HEADER = "<!-- Generated by scripts/generate_reference_docs.py. Do not edit by hand. -->\n\n"

DOMAINS = {
    "identity": "Identity and access",
    "audit": "Audit",
    "reference": "Reference data (customers, SLA terms, agents)",
    "tickets": "Tickets, ingestion and PII",
    "knowledge": "Knowledge base and retrieval",
    "processing": "Classification, routing, duplicates and model usage",
    "approvals": "Human approval and learned memory",
    "settings": "Runtime configuration",
    "evaluation": "Evaluation and cost",
}


# --------------------------------------------------------------------------- API


def _permissions(dependant: Any) -> list[str]:
    found: list[str] = []
    call = getattr(dependant, "call", None)
    if call is not None and getattr(call, "__qualname__", "").startswith("require.") and call.__closure__:
        for cell in call.__closure__:
            if isinstance(cell.cell_contents, Permission):
                found.append(cell.cell_contents.value)
    for sub in getattr(dependant, "dependencies", []):
        found.extend(_permissions(sub))
    return found


def _authenticated(dependant: Any) -> bool:
    call = getattr(dependant, "call", None)
    if call is not None and getattr(call, "__name__", "") == "get_principal":
        return True
    return any(_authenticated(sub) for sub in getattr(dependant, "dependencies", []))


def _api_routes(routes: list[Any], prefix: str = "") -> list[tuple[str, APIRoute]]:
    """Flatten routes; FastAPI >= 0.16x wraps included routers lazily (`original_router`)."""
    found: list[tuple[str, APIRoute]] = []
    for route in routes:
        if isinstance(route, APIRoute):
            found.append((prefix + route.path, route))
        elif hasattr(route, "original_router"):
            context = getattr(route, "include_context", None)
            found.extend(_api_routes(route.original_router.routes, prefix + getattr(context, "prefix", "")))
    return found


def api_docs(app: Any) -> str:
    rows: dict[str, list[str]] = defaultdict(list)
    count = 0
    for path, route in sorted(_api_routes(app.routes), key=lambda pr: pr[0]):
        perms = sorted(set(_permissions(route.dependant)))
        if perms:
            access = ", ".join(f"`{p}`" for p in perms)
        elif _authenticated(route.dependant):
            access = "any signed-in user"
        else:
            access = "public"
        summary = (route.description or "").strip().splitlines()[0] if route.description else ""
        summary = summary or route.summary or route.name.replace("_", " ").capitalize()
        group = path.removeprefix("/api/v1").strip("/").split("/")[0] or "health"
        for method in sorted(route.methods - {"HEAD", "OPTIONS"}):
            rows[group].append(f"| `{method}` | `{path}` | {access} | {summary.replace('|', '/')} |")
            count += 1
    out = [
        HEADER,
        "# API reference\n\n",
        "Versioned REST API under `/api/v1`. Interactive documentation is served at `/api/docs`;\n",
        "the machine-readable document is [openapi.json](openapi.json).\n\n",
        "- **Authentication:** `POST /api/v1/auth/login` sets an httpOnly session cookie (a JWT backed by a\n",
        "  revocable server-side session). The browser reaches the API only through the Next.js same-origin proxy.\n",
        "- **Authorisation:** the *Access* column is the permission checked in code (`app/core/rbac.py`);\n",
        "  see [the role matrix](../security/rbac.md). Every data query is additionally filtered to the\n",
        "  caller's region scope (India / UAE).\n",
        '- **Errors:** `{"error": {"code", "message", "request_id"}}`. List endpoints are paginated\n',
        "  (`page`, `page_size`) and return `{items, total, page, page_size}`.\n\n",
        f"{count} operations.\n",
    ]
    for group in sorted(rows):
        out.append(f"\n## {group}\n\n| Method | Path | Access | Summary |\n|---|---|---|---|\n")
        out.append("\n".join(rows[group]) + "\n")
    return "".join(out)


# --------------------------------------------------------------------------- database


def _type(column: Any) -> str:
    name = type(column.type).__name__.lower()
    return {"enum": "enum", "jsonb": "jsonb", "vector": "vector"}.get(name, name)


def database_docs() -> str:
    tables_by_domain: dict[str, list[Any]] = defaultdict(list)
    domain_of: dict[str, str] = {}
    for mapper in Base.registry.mappers:
        table = mapper.local_table
        domain = mapper.class_.__module__.rsplit(".", 1)[-1]
        if table.name not in domain_of:
            domain_of[table.name] = domain
            tables_by_domain[domain].append(table)

    cross: dict[tuple[str, str], int] = defaultdict(int)
    for table in Base.metadata.sorted_tables:
        for fk in table.foreign_keys:
            a, b = domain_of.get(fk.column.table.name), domain_of.get(table.name)
            if a and b and a != b:
                cross[(a, b)] += 1

    out = [
        HEADER,
        "# Database\n\n",
        f"PostgreSQL 16 with pgvector. {len(Base.metadata.tables)} tables, created only by Alembic migrations\n",
        "(`backend/alembic/versions/`). Constraint names follow a fixed convention so migrations diff cleanly.\n\n",
        "Database-enforced rules worth knowing:\n\n",
        "- `audit_logs` is append-only: a trigger rejects `UPDATE` and `DELETE`.\n",
        "- PII originals live only in `pii_vault` (Fernet-encrypted, region-tagged, with a retention date);\n",
        "  `source_records.raw_encrypted` holds the encrypted original record. Ticket subjects, bodies, messages,\n",
        "  events, logs and drafts hold `<TYPE_n>` tokens only.\n",
        "- Check constraints restrict regions (`IN`, `UAE`), priorities, statuses and effective-date windows.\n\n",
        "## Domains\n\n```mermaid\nflowchart LR\n",
    ]
    for domain in DOMAINS:
        if domain in tables_by_domain:
            n = len(tables_by_domain[domain])
            out.append(f'  {domain}["{DOMAINS[domain]}<br/>{n} table{"s" if n != 1 else ""}"]\n')
    for (a, b), n in sorted(cross.items()):
        out.append(f"  {a} -->|{n} FK| {b}\n")
    out.append("```\n\nArrows point from the referenced domain to the referencing one.\n")

    for domain, title in DOMAINS.items():
        tables = tables_by_domain.get(domain)
        if not tables:
            continue
        names = {t.name for t in tables}
        out.append(f"\n## {title}\n\n```mermaid\nerDiagram\n")
        for table in tables:
            out.append(f"  {table.name} {{\n")
            for column in table.columns:
                keys = []
                if column.primary_key:
                    keys.append("PK")
                if column.foreign_keys:
                    keys.append("FK")
                key = f" {','.join(keys)}" if keys else ""
                out.append(f"    {_type(column)} {column.name}{key}\n")
            out.append("  }\n")
        for table in tables:
            for fk in sorted(table.foreign_keys, key=lambda f: f.parent.name):
                parent = fk.column.table.name
                if parent in names:
                    card = "|o--o{" if fk.parent.nullable else "||--o{"
                    out.append(f'  {parent} {card} {table.name} : "{fk.parent.name}"\n')
        out.append("```\n\n")
        external = [
            f"`{t.name}.{fk.parent.name}` → `{fk.column.table.name}`"
            for t in tables
            for fk in sorted(t.foreign_keys, key=lambda f: f.parent.name)
            if fk.column.table.name not in names
        ]
        if external:
            out.append("References to other domains: " + ", ".join(external) + ".\n")
    return "".join(out)


# --------------------------------------------------------------------------- RBAC


def rbac_docs() -> str:
    roles = list(ROLE_PERMISSIONS)
    out = [
        HEADER,
        "# Role and permission matrix\n\n",
        "Defined in `backend/app/core/rbac.py` and enforced per endpoint (see the *Access* column of the\n",
        "[API reference](../api/README.md)). Users also carry region scopes (`IN`, `UAE`); every query is\n",
        "filtered to them, and records with an unknown region are visible only to users scoped to both.\n\n",
        "| Permission | " + " | ".join(r.value for r in roles) + " |\n",
        "|---|" + "---|" * len(roles) + "\n",
    ]
    for permission in Permission:
        cells = ["yes" if permission in ROLE_PERMISSIONS[r] else "" for r in roles]
        out.append(f"| `{permission.value}` | " + " | ".join(cells) + " |\n")
    out.append(
        "\n`pii:reveal` belongs to the DPO alone; admins are deliberately excluded. Approving a draft for "
        "routing rules R6/R7 additionally requires a second person (the last editor cannot approve).\n"
    )
    return "".join(out)


def main() -> None:
    app = create_app()
    targets = {
        ROOT / "docs" / "api" / "README.md": api_docs(app),
        ROOT / "docs" / "api" / "openapi.json": json.dumps(app.openapi(), indent=2, sort_keys=True) + "\n",
        ROOT / "docs" / "database" / "README.md": database_docs(),
        ROOT / "docs" / "security" / "rbac.md": rbac_docs(),
    }
    for path, text in targets.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8", newline="\n")
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
